/** 특정 충전소와 연결된 제휴 매장 목록 */
export function partnerStoresForStation(stationId: string | null | undefined): PartnerStore[] {
  if (!stationId) return [];
  return PARTNER_STORES.filter((store) => store.stationIds.includes(stationId));
}

/** 리워드 id로 연결된 제휴 매장 찾기 */
export function partnerStoreForReward(rewardId: string | undefined): PartnerStore | null {
  if (!rewardId) return null;
  return PARTNER_STORES.find((store) => store.rewardId === rewardId) ?? null;
}

export function partnerStoreById(storeId: string | null | undefined): PartnerStore | null {
  if (!storeId) return null;
  return PARTNER_STORES.find((store) => store.id === storeId) ?? null;
}
