/** 특정 좌표에서 가장 가까운 관광지들 */
export function attractionsNear(
  origin: { latitude: number; longitude: number },
  limit = 3
): Attraction[] {
  return [...ATTRACTIONS]
    .map((a) => ({
      a,
      d: (a.lat - origin.latitude) ** 2 + (a.lng - origin.longitude) ** 2,
    }))
    .sort((x, y) => x.d - y.d)
    .slice(0, limit)
    .map((x) => x.a);
}
